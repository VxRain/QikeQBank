/**
 * 柱状图高度归一（首页「近 7 天练习趋势」与复习页「未来 7 天到期预测」共用）
 *
 * ── 为什么必须共用 ──────────────────────────────────────────────
 * 两处都是「按天计数的小柱状图」，但曾经各写一套：复习页 0 值给 0 高度，
 * 首页 0 值给 2% 残桩 + `min-h-[2px]`。同一个用户在两个页面看到同一份数据、
 * 却是两套视觉语义——「0 题那天有一根小柱子」和「0 题那天什么都没有」，
 * 用户没法据此判断哪张图在说真话。
 *
 * ── 口径（改这里之前先读）───────────────────────────────────────
 * 1. **峰值归一**：`count / 本组最大值` → 谁最大谁满格。不按绝对刻度，
 *    因为两类数据量级差极大（复习卡可能 1~5 题/天，重度用户 100+ 题/天），
 *    绝对刻度会让轻度用户看到 7 根 1~2px 的线、整块区域像「没数据」。
 *    代价是绝对量不可知，故两处都必须在标题旁给「共 N 题 · 峰值 M/天」这类文字锚定。
 * 2. **0 值 = 0 高度，不给残桩**：0 题那天若画 2%，就与「有少量」在视觉上无法区分。
 * 3. **非 0 至少 BAR_MIN_PCT**：否则 1/300 四舍五入成 0，看起来像那天没有安排。
 *
 * @param {number} count 当天数值
 * @param {number} max 本组峰值（调用方按 `Math.max(1, ...counts)` 传入）
 * @returns {number} 0~100 的百分比；脏数据一律按 0 处理，不产生 NaN
 */
export const BAR_MIN_PCT = 2

export function barPct(count, max) {
  const n = Math.max(0, Math.round(Number(count) || 0))
  const m = Math.max(1, Math.round(Number(max) || 0))
  if (n <= 0) return 0
  // 封顶 100：正常数据下 count <= max 恒成立，但 min-h/百分比一旦大于 100%
  // 柱会超出轨道高度。这里的下限是防御，不是算法（max 与 count 应由同一份数据算出）。
  return Math.min(100, Math.max(BAR_MIN_PCT, Math.round((n / m) * 100)))
}
